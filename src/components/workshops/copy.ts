/**
 * 한 문장이 끝나면 줄을 바꾼다(대표 지시, 전 BU 공통 규칙).
 * village copy.ts 와 동일 구현 — 약어 마침표를 카피에 쓰지 않는다.
 */
export function splitSentences(text: string): string[] {
  return text
    .replace(/([。！？])\s*/g, "$1\n")
    .replace(/([.!?])\s+/g, "$1\n")
    .split("\n")
    .map((s) => s.trim())
    .filter(Boolean);
}

