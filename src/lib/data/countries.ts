/** 표시용 라벨(현재 언어 우선, 양쪽 병기). 저장 시 nationality 라벨로 사용. */
export function countryLabel(code: string | null | undefined, lang: "ko" | "en" = "ko"): string {
  const c = countryByCode(code);
  if (!c) return "";
  return lang === "ko" ? c.ko : c.en;
}
